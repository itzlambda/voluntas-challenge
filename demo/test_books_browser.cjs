// Run with Playwright available: node demo/test_books_browser.cjs http://127.0.0.1:PORT
const assert = require('node:assert/strict');
const {chromium} = require('playwright');
const {record} = require('./book-fixture.cjs');
const base = process.argv[2];
const id = `0x${'a'.repeat(64)}`;
(async () => {
  const browser = await chromium.launch({headless: true});
  try {
    const page = await browser.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    // Records whether a loading row was ever shown; synthetic details replace them after 400 ms.
    await page.addInitScript(() => {
      window.sawSpinner = false;
      new MutationObserver(() => { if (document.querySelector('[data-market-list] .market-spinner')) window.sawSpinner = true; })
        .observe(document, {childList: true, subtree: true});
    });
    await page.goto(`${base}/sockets?socket-demo=1`);
    await page.locator('.socket-id').first().click();
    assert.equal(await page.locator('dialog').evaluate(d => d.open), true);
    assert.equal(await page.locator('[data-socket-plot] .uplot').count(), 1);
    await page.locator('[data-market-list] button:enabled').first().waitFor();
    assert.equal(await page.evaluate(() => window.sawSpinner), true, 'rows start as IDs with spinners');
    assert.equal(await page.locator('[data-market-list] button').count(), 5);
    assert.equal(await page.locator('[data-market-page]').innerText(), '1 to 5 of 23');
    assert.equal(await page.getByText('Select a market to watch its live order book.').isVisible(), true);
    await page.locator('[data-market-list] button:enabled').first().click();
    await page.locator('[data-book-status]').filter({hasText: /^Live \(synthetic\)$/}).waitFor();
    assert.equal(await page.locator('[data-market-list] button[aria-pressed="true"]').count(), 1);
    assert.equal(await page.locator('.ladder-row.ask').count(), 8);
    assert.equal(await page.locator('.ladder-row.bid').count(), 8);
    assert.match(await page.locator('.ladder-mid').innerText(), /% chance · spread /);
    await page.locator('[data-book-outcomes] button').nth(1).click();
    assert.equal(await page.locator('[data-book-outcomes] button').nth(1).getAttribute('aria-pressed'), 'true');
    await page.locator('.ladder-row.ask').first().waitFor();
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('dialog').evaluate(d => d.open), false);
    assert.equal(await page.evaluate(() => document.activeElement.classList.contains('socket-id')), true, 'Escape restores focus');
    await page.locator('.socket-id').first().click();
    const bounds = await page.locator('dialog').boundingBox();
    await page.mouse.click(bounds.x + 4, bounds.y + 4);
    assert.equal(await page.locator('dialog').evaluate(d => d.open), true, 'inside padding does not dismiss');
    await page.mouse.move(bounds.x + 4, bounds.y + 4); await page.mouse.down();
    await page.mouse.move(2, 2); await page.mouse.up();
    assert.equal(await page.locator('dialog').evaluate(d => d.open), true, 'dragging out from inside does not dismiss');
    await page.mouse.click(2, 2);
    await page.waitForFunction(() => !document.querySelector('dialog').open);
    assert.equal(await page.evaluate(() => document.activeElement.classList.contains('socket-id')), true, 'outside dismissal restores focus');
    await page.setViewportSize({width: 390, height: 844});
    await page.locator('.socket-id').first().click();
    await page.locator('[data-market-list] button:enabled').first().click();
    await page.locator('.ladder-row.ask').first().waitFor();
    assert.ok(await page.locator('dialog').evaluate(d => d.scrollWidth <= d.clientWidth + 1));
    await page.getByRole('button', {name: 'Close', exact: true}).click();
    assert.equal(await page.evaluate(() => document.activeElement.classList.contains('socket-id')), true, 'Close restores focus');

    let connections = 0, directoryRequests = 0, closed = 0;
    const sockets = [], gammaBatches = [];
    let gammaMode = 'ok';
    const marketIds = [id, ...Array.from({length: 44}, (_, i) => `0x${(i + 1).toString(16).padStart(64, '0')}`)];
    await page.route('**/api/demo/config', route => route.fulfill({json: {stream_origin: 'wss://stream.example.com'}}));
    await page.route('https://stream.example.com/sockets/*/markets', route => {
      directoryRequests++;
      return route.fulfill({headers: {'Access-Control-Allow-Origin': '*'}, json: {markets: marketIds}});
    });
    await page.route('https://gamma-api.polymarket.com/markets?**', route => {
      if (gammaMode === 'dns') return route.abort('namenotresolved');
      if (gammaMode === 'error') return route.fulfill({status: 500, headers: {'Access-Control-Allow-Origin': '*'}, body: 'upstream'});
      const params = new URL(route.request().url()).searchParams, requested = params.getAll('condition_ids');
      gammaBatches.push(requested);
      assert.equal(Number(params.get('limit')), requested.length, 'Gamma limit covers the entire batch');
      assert.deepEqual(params.getAll('version'), ['v1', 'v2']);
      assert.equal(params.get('closed'), 'any');
      const rows = requested.map((conditionId, i) => ({conditionId,
        question: conditionId === id ? 'Live wire test market' : `Other test market ${i}`,
        outcomes: '["Yes","No"]', outcomePrices: '["0.45","0.55"]', clobTokenIds: '["123","456"]'}));
      return route.fulfill({headers: {'Access-Control-Allow-Origin': '*'}, json: rows});
    });
    await page.routeWebSocket('wss://stream.example.com/**', socket => {
      connections++; sockets.push(socket);
      socket.onClose(() => closed++);
      socket.onMessage(message => {
        assert.deepEqual(JSON.parse(message), {op: 'subscribe', books: ['123', '456']});
        // A pre-snapshot update must remain invisible.
        socket.send(record(2, '123', {price: 123n, quantity: 999n}));
      });
    });
    await page.route('**/api/demo/sockets', route => route.fulfill({json: {schema_version: 1, status: 'live', retained: false, values_at: Date.now() / 1000, age_seconds: 0, sockets: [{id: 0, pool: 'primary', connected: true, markets: 1, state: 'connected', events_per_second: 2}]}}));
    await page.goto(`${base}/sockets`);
    await page.locator('.socket-id').first().click();
    await page.waitForFunction(() => document.querySelectorAll('[data-market-list] button:enabled').length === 5);
    assert.deepEqual(gammaBatches, [marketIds.slice(0, 5)], 'only the visible page is looked up');
    assert.match(await page.locator('[data-market-list] button').first().innerText(), /Live wire test market\s*Yes 45%/);
    assert.equal(await page.locator('[data-market-page]').innerText(), '1 to 5 of 45');
    await page.locator('[data-market-next]').click();
    await page.waitForFunction(() => document.querySelectorAll('[data-market-list] button:enabled').length === 5);
    assert.equal(gammaBatches.length, 2); assert.deepEqual(gammaBatches[1], marketIds.slice(5, 10));
    for (let i = 0; i < 7; i++) await page.locator('[data-market-next]').click();
    assert.equal(await page.locator('[data-market-page]').innerText(), '41 to 45 of 45');
    assert.equal(await page.locator('[data-market-next]').isDisabled(), true);
    for (let i = 0; i < 8; i++) await page.locator('[data-market-previous]').click();
    assert.equal(await page.locator('[data-market-previous]').isDisabled(), true);
    await page.waitForFunction(() => document.querySelectorAll('[data-market-list] button:enabled').length === 5);
    assert.equal(gammaBatches.length, 9, 'pages already looked up are not requested again');
    await page.getByRole('button', {name: /Live wire test market/}).click();
    await page.getByText('Waiting for the first snapshot. This can take up to 60 seconds.', {exact: true}).waitFor();
    assert.equal(await page.locator('.ladder-wait').count(), 1);
    assert.equal(await page.locator('.ladder-row').count(), 0);
    sockets[0].send(Buffer.concat([record(1), record(1, '456')]));
    await page.locator('[data-book-status]').filter({hasText: /^Live$/}).waitFor();
    assert.deepEqual(await page.locator('.ladder-row.ask').allInnerTexts(), ['55¢\n2.5']);
    assert.deepEqual(await page.locator('.ladder-row.bid').allInnerTexts(), ['45.0001¢\n12,345,678,901.234567']);
    assert.equal(await page.locator('.ladder-mid').innerText(), '50% chance · spread 9.9999¢');
    await page.locator('[data-market-next]').click();
    assert.equal(connections, 1, 'paging leaves the selected stream running');
    assert.equal(await page.locator('[data-book-title]').innerText(), 'Live wire test market');
    await page.locator('[data-market-previous]').click();
    assert.ok(await page.locator('dialog').evaluate(d => d.scrollWidth <= d.clientWidth + 1), 'large exact quantities fit on mobile');
    await page.evaluate(() => {
      window.bookStatusMutations = 0;
      window.bookStatusObserver = new MutationObserver(list => window.bookStatusMutations += list.length);
      window.bookStatusObserver.observe(document.querySelector('[data-book-status]'), {childList: true, characterData: true, subtree: true});
      window.firstLevel = document.querySelector('.ladder-row.ask');
    });
    sockets[0].send(record(1));
    await page.waitForTimeout(200);
    assert.equal(await page.evaluate(() => window.bookStatusMutations), 0, 'unchanged live status is not reannounced');
    assert.equal(await page.evaluate(() => window.firstLevel === document.querySelector('.ladder-row.ask')), true, 'level rows remain stable');
    await page.evaluate(() => window.bookStatusObserver.disconnect());
    sockets[0].send(record(2, '123', {quantity: 777000000n}));
    await page.waitForFunction(() => document.querySelector('.ladder-row.bid').classList.contains('flash'));
    assert.equal(await page.locator('.ladder-row.bid').innerText(), '45.0001¢\n777');
    sockets[0].send(record(2, '123', {quantity: 0n}));
    await page.waitForFunction(() => document.querySelector('[data-bids]').textContent === 'No bids');
    assert.equal(await page.locator('.ladder-mid').innerText(), 'No spread while a side is empty');
    await page.locator('[data-book-outcomes] button', {hasText: 'No'}).click();
    assert.deepEqual(await page.locator('.ladder-row.bid').allInnerTexts(), ['45.0001¢\n12,345,678,901.234567'], 'the No outcome shows its own book');
    await page.locator('[data-book-outcomes] button', {hasText: 'Yes'}).click();
    sockets[0].close({code: 1013, reason: 'test reconnect'});
    await page.getByText('Reconnected. Showing the last known orders until a new snapshot arrives, up to 60 seconds.', {exact: true}).waitFor();
    assert.equal(connections, 2);
    assert.equal(await page.locator('.ladder.ladder-old').count(), 1, 'the last known book stays visible, dimmed');
    assert.deepEqual(await page.locator('.ladder-row.ask').allInnerTexts(), ['55¢\n2.5'], 'the new session\'s pre-snapshot update is ignored');
    sockets[1].send(Buffer.concat([record(1), record(1, '456')]));
    await page.locator('[data-book-status]').filter({hasText: /^Live$/}).waitFor();
    await page.waitForFunction(() => !document.querySelector('.ladder.ladder-old'), null, {timeout: 2000}); // a fresh snapshot replaces the old book
    await page.mouse.click(2, 2);
    await page.waitForTimeout(200);
    assert.equal(await page.locator('dialog').evaluate(d => d.open), false, 'outside click closes live books');
    assert.ok(closed >= 1, 'outside dismissal closes the stream');
    await page.locator('.socket-id').first().click();
    await page.getByRole('button', {name: /Live wire test market/}).waitFor();
    assert.equal(directoryRequests, 2, 'reopening fetches current assignments');
    await page.keyboard.press('Escape');
    // Hidden tabs keep the subscription and its books. A close while hidden reconnects only once visible.
    const visibility = value => page.evaluate(state => {
      Object.defineProperty(document, 'visibilityState', {configurable: true, value: state});
      document.dispatchEvent(new Event('visibilitychange'));
    }, value);
    await page.locator('.socket-id').first().click();
    await page.getByRole('button', {name: /Live wire test market/}).click();
    await page.waitForFunction(() => document.querySelector('[data-book-status]').textContent.includes('Waiting for the first snapshot'));
    const beforeHidden = connections, closedBeforeHidden = closed, live = sockets[sockets.length - 1];
    live.send(Buffer.concat([record(1), record(1, '456')]));
    await page.locator('[data-book-status]').filter({hasText: /^Live$/}).waitFor();
    await visibility('hidden');
    live.send(record(2, '123', {quantity: 321000000n}));
    await page.waitForTimeout(400);
    assert.equal(connections, beforeHidden, 'hiding does not reconnect');
    assert.equal(closed, closedBeforeHidden, 'hiding keeps the socket open');
    await visibility('visible');
    await page.waitForFunction(() => [...document.querySelectorAll('.ladder-row.bid')].some(row => row.textContent === '45.0001¢321'));
    assert.equal(await page.locator('[data-book-status]').innerText(), 'Live', 'no snapshot wait after returning');
    await visibility('hidden');
    live.close({code: 1013, reason: 'closed while hidden'});
    await page.waitForTimeout(1600);
    assert.equal(connections, beforeHidden, 'no reconnect while hidden');
    await visibility('visible');
    await page.getByText('Reconnected. Showing the last known orders until a new snapshot arrives, up to 60 seconds.', {exact: true}).waitFor();
    assert.equal(connections, beforeHidden + 1, 'reconnects once visible');
    await page.keyboard.press('Escape');
    // An unresolvable Polymarket host gets its own explanation; other failures do not blame the region.
    gammaMode = 'dns';
    await page.locator('.socket-id').first().click();
    const problem = page.locator('[data-market-status].lookup-problem');
    await problem.waitFor();
    assert.equal(await problem.innerText(), 'Could not reach Polymarket to load market details. Polymarket may be blocked in your region or on your network.');
    assert.match(await page.locator('[data-market-list] button').first().innerText(), /Details unavailable/);
    assert.equal(await page.locator('[data-market-list] button:enabled').count(), 0);
    gammaMode = 'error';
    await page.locator('[data-market-retry]').click();
    await page.getByText('Polymarket did not send market details. Try Refresh.', {exact: true}).waitFor();
    gammaMode = 'ok';
    await page.locator('[data-market-retry]').click();
    await page.getByRole('button', {name: /Live wire test market/}).waitFor();
    assert.equal(await page.locator('[data-market-status].lookup-problem').count(), 0, 'a successful lookup clears the warning');
    assert.equal(await page.locator('[data-market-status]').innerText(), '45 markets. Select one to watch its live order book.');
    await page.keyboard.press('Escape');
    await page.route('**/api/demo/config', route => route.fulfill({json: {stream_origin: null}}));
    await page.locator('.socket-id').first().click();
    await page.getByText('Live order books are not enabled on this deployment.', {exact: true}).waitFor();
    await page.keyboard.press('Escape');
    await page.route('**/book-view.js', route => route.abort());
    await page.goto(`${base}/sockets`);
    await page.locator('.socket-id').first().click();
    await page.getByText('Market viewing could not be loaded. Reload the page to retry.', {exact: true}).waitFor();
    await page.keyboard.press('Escape');
    assert.deepEqual(errors, []);
    console.log('Browser checks passed: synthetic popup/history/ladder/outcome toggle, page-by-page Gamma lookup, unreachable-Polymarket message, mobile overflow, exact SBE snapshots/updates, waiting state, reconnect with last known book, hidden-tab keepalive and deferred reconnect, close cleanup, and assignment refresh.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
